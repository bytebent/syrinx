// Builds reference/syrinx-maps.js: the source oscillator measured over its control plane.
// Run: node tools/make-maps.js   (about a minute)
//
// The oscillator, at time scale γ = 1 (Sitt et al. 2010 form):
//   x' = v,   v' = α + β·x + x² − x·v − x³ − x²·v
// With γ, time runs γ times faster, so the frequency in Hz is γ · f, where f is measured here.
//
// Rows: Regime r in [0, 1], β = BETA_LO + (BETA_HI − BETA_LO) · r.
// Columns: drive d past the onset line, d = D_MAX · u², u from sqrt(D_MIN / D_MAX) to 1.
// The onset line α_on(β) is exact: Hopf at α = 0 for β ≤ −0.25, otherwise the saddle-node of the
// fixed points (a SNILC bifurcation), where the rest state is destroyed.
// Each point stores f (cycles per unit time), spectral content (energy-weighted mean harmonic
// number; 1 = pure tone), the AC rms and the mean of x.
'use strict';
const fs = require('fs'), path = require('path');
const { core } = require(path.join(__dirname, '..', 'reference', 'syrinx-engine.js'));
const { BETA_LO, BETA_HI, ROWS, COLS, alphaOn, rk4 } = core;

const H = 0.05;                     // integration step for the map (RK4: about 0.002 cent here)
const HARM = 64;

function measure(a, b, s, dHint) {
  // settle: long enough for the slow amplitude convergence close to a Hopf onset
  const settle = Math.min(60000, Math.max(3000, 8 / Math.max(dHint, 1e-6)));
  for (let t = 0; t < settle; t += H) rk4(a, b, s, H);
  // rough period from mean crossings over a stretch
  const probe = Math.round(2500 / H);
  let mean = 0; const c0 = s.slice();
  for (let i = 0; i < probe; i++) { rk4(a, b, c0, H); mean += c0[0]; }
  mean /= probe;
  // record until PERIODS whole periods lie between upward crossings of the mean;
  // xs[i] is the state after step i + 1
  const PERIODS = 40;
  const xs = [];
  const cross = [];
  let prev = s[0];
  while (cross.length <= PERIODS) {
    if (xs.length > 2e7) return null;
    rk4(a, b, s, H);
    const x = s[0];
    // crossing between sample positions (xs.length − 1) and xs.length, in steps
    if (prev < mean && x >= mean) cross.push(xs.length - 1 + (mean - prev) / (x - prev));
    xs.push(x);
    prev = x;
  }
  const T = (cross[PERIODS] - cross[0]) / PERIODS * H;
  // statistics over the samples inside the whole periods
  const i0 = Math.ceil(cross[0]), i1 = Math.floor(cross[PERIODS]);
  const n = i1 - i0;
  let m = 0;
  for (let k = i0; k < i1; k++) m += xs[k];
  m /= n;
  let v = 0;
  for (let k = i0; k < i1; k++) { const q = xs[k] - m; v += q * q; }
  const rms = Math.sqrt(v / n);
  let num = 0, den = 0;
  for (let hn = 1; hn <= HARM; hn++) {
    let re = 0, im = 0;
    const w = 2 * Math.PI * hn * H / T;
    for (let k = i0; k < i1; k++) { const q = xs[k] - m, ph = w * k; re += q * Math.cos(ph); im += q * Math.sin(ph); }
    const e = re * re + im * im;
    num += hn * e; den += e;
  }
  return { f: 1 / T, sci: num / den, rms, mean: m };
}

const f = new Float64Array(ROWS * COLS), sci = new Float64Array(ROWS * COLS);
const rms = new Float64Array(ROWS * COLS), mean = new Float64Array(ROWS * COLS);
const t0 = Date.now();
for (let r = 0; r < ROWS; r++) {
  const b = BETA_LO + (BETA_HI - BETA_LO) * r / (ROWS - 1);
  const aOn = alphaOn(b);
  const s = [0.3, 0];
  // strongest drive first: each next point starts from the last one's cycle
  for (let c = COLS - 1; c >= 0; c--) {
    const d = core.colDrive(c);
    const q = measure(aOn - d, b, s, d);
    if (!q) throw new Error('no oscillation at row ' + r + ', column ' + c + ' (β ' + b + ', d ' + d + ')');
    const k = r * COLS + c;
    f[k] = q.f; sci[k] = q.sci; rms[k] = q.rms; mean[k] = q.mean;
  }
  process.stdout.write('\rrow ' + (r + 1) + '/' + ROWS + '  ' + ((Date.now() - t0) / 1000).toFixed(0) + ' s');
}
process.stdout.write('\n');

const fmt = (a, sig) => '[' + Array.from(a, x => +x.toPrecision(sig)).join(',') + ']';
const out = `// Generated by tools/make-maps.js — do not edit. ${ROWS} rows (Regime) × ${COLS} columns (drive).
(function (root) {
  'use strict';
  const MAP = {
    rows: ${ROWS}, cols: ${COLS},
    f: ${fmt(f, 9)},
    sci: ${fmt(sci, 4)},
    rms: ${fmt(rms, 5)},
    mean: ${fmt(mean, 6)},
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = MAP;
  else root.SyrinxMap = MAP;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
const file = path.join(__dirname, '..', 'reference', 'syrinx-maps.js');
fs.writeFileSync(file, out);
console.log('reference/syrinx-maps.js', Math.round(out.length / 1024), 'KB');
